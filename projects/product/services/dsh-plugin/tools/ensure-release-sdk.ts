/** Local release preparation only; never installs or activates a desktop. */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { prepareReleaseSdk, releaseSdkEnvironment, releaseSdkPlan, RELEASE_SDK_PNPM_VERSION } from './prepare-release-sdk.ts';
import { ownedBuildRoot, sha256, validatePreparedSourceSdk } from './prepare-source-sdk.ts';
import { resolvePeerNpm } from './buildr-peer.ts';
import { downloadRegistry, installSdkDependencies } from './release-sdk-downloads.ts';

const service = path.resolve(import.meta.dirname, '..');
const recipeFiles = ['ensure-release-sdk.ts', 'prepare-release-sdk.ts', 'release-sdk-downloads.ts', 'prepare-source-sdk.ts',
  'sdk-baselines.ts', 'sdk-require.ts', 'dsh-host-compatibility.ts'];
const regular = (file: string) => {
  const stat = fs.lstatSync(file);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error(`SDK cache requires an ordinary file: ${file}`);
  return fs.readFileSync(file);
};

/** Include installed bytes and link destinations, not only a dependency lockfile. */
export function sdkDependencyIdentity(root: string): string {
  if (!fs.lstatSync(root).isDirectory() || fs.lstatSync(root).isSymbolicLink()) throw new Error('SDK dependency directory must be owned.');
  root = fs.realpathSync(root);
  const rows: any[] = [];
  const visit = (directory: string) => {
    for (const name of fs.readdirSync(directory).sort()) {
      const file = path.join(directory, name), stat = fs.lstatSync(file);
      const relative = path.relative(root, file).split(path.sep).join('/');
      if (stat.isSymbolicLink()) {
        const link = fs.readlinkSync(file), lexical = path.resolve(path.dirname(file), link);
        const owner = path.dirname(root), local = path.relative(owner, lexical);
        if (path.isAbsolute(local) || local === '..' || local.startsWith(`..${path.sep}`)) throw new Error('SDK dependency link escapes its owned install.');
        // pnpm can leave links to optional packages absent on this platform.
        // Preserve that fact; a later appearance changes the inventory.
        const present = fs.existsSync(file);
        const target = present ? fs.realpathSync(file) : lexical, nested = path.relative(owner, target);
        if (path.isAbsolute(nested) || nested === '..' || nested.startsWith(`..${path.sep}`)) throw new Error('SDK dependency link escapes its owned install.');
        rows.push([relative, 'link', link, present]);
      } else if (stat.isDirectory()) visit(file);
      else if (stat.isFile()) rows.push([relative, stat.mode & 0o111, sha256(fs.readFileSync(file))]);
      else throw new Error('SDK dependency inventory contains a special file.');
    }
  };
  visit(root);
  return sha256(JSON.stringify(rows));
}

export function sdkPreparationKey(input: {
  manifest: unknown; recipe: unknown; nodeVersion: string; nodeSha256: string;
  pnpmVersion: string; pnpmSha256: string; platform: string; arch: string;
}): string {
  return sha256(JSON.stringify(input));
}

/** The cache is only a pointer; real receipts, installed dependencies and generated bytes decide reuse. */
export async function ensureReleaseSdk(input: { node: string; pnpm: string }, dependencies: any = {}): Promise<any> {
  const root = dependencies.serviceRoot ?? service;
  const build = ownedBuildRoot(root), plan = (dependencies.plan ?? releaseSdkPlan)();
  const node = fs.realpathSync(input.node), pnpm = fs.realpathSync(input.pnpm);
  const version = dependencies.version ?? ((executable: string, args: string[]) =>
    execFileSync(executable, args, { encoding: 'utf8', timeout: 30_000 }).trim());
  const pnpmVersion = version(node, [pnpm, '--version']);
  if (pnpmVersion !== RELEASE_SDK_PNPM_VERSION) throw new Error(`SDK preparation requires pnpm ${RELEASE_SDK_PNPM_VERSION}.`);
  const key = sdkPreparationKey({ manifest: plan.manifest,
    recipe: recipeFiles.map(file => [file, sha256(regular(path.join(root, 'tools', file)))]),
    nodeVersion: version(node, ['--version']), nodeSha256: sha256(regular(node)),
    pnpmVersion, pnpmSha256: (dependencies.toolIdentity ?? (() => sdkDependencyIdentity(path.dirname(path.dirname(pnpm)))))(), platform: process.platform, arch: process.arch });
  const cache = path.join(build, `release-sdk-cache-${key}.json`);
  const lock = `${cache}.lock`, descriptor = fs.openSync(lock, 'wx', 0o600), owner = fs.fstatSync(descriptor);
  try {
    const validate = dependencies.validate ?? validatePreparedSourceSdk;
    const inventory = dependencies.inventory ?? sdkDependencyIdentity;
    const inspect = (sdk: string) => {
      const receipt = validate(sdk, root);
      if (JSON.stringify(receipt.baseline) !== JSON.stringify(plan.manifest.upstream)
        || receipt.patchSha256 !== plan.manifest.patch.sha256
        || receipt.sourceManifest.sha256 !== sha256(regular(plan.manifestFile))) throw new Error('Cached SDK inputs differ from the fixed release plan.');
      return { lock: sha256(regular(path.join(receipt.sourceCheckout, 'pnpm-lock.yaml'))),
        dependencies: inventory(path.join(receipt.sourceCheckout, 'node_modules')) };
    };
    if (fs.existsSync(cache)) {
      try {
        const saved = JSON.parse(regular(cache).toString('utf8'));
        if (saved.key === key && JSON.stringify(inspect(saved.sdk)) === JSON.stringify(saved.installed)) {
          return { status: 'prepared', sdk: saved.sdk, disposition: 'reused', key, runtimeActivated: false, desktopValidated: false };
        }
      } catch (error: any) { console.error(`[dsh-sdk] retained preparation is invalid: ${String(error.message).slice(0, 500)}`); }
    }
    console.error('[dsh-sdk] prepare exact source, frozen dependencies and SDK artifacts locally');
    const result = await (dependencies.prepare ?? prepareReleaseSdk)({ node, pnpm });
    const saved = { key, sdk: result.sdk, installed: inspect(result.sdk) };
    // Serial local preparation only. Never follow an externally replaced cache alias.
    if (fs.existsSync(cache)) regular(cache);
    const temporary = `${cache}.${process.pid}.tmp`;
    fs.writeFileSync(temporary, JSON.stringify(saved) + '\n', { flag: 'wx', mode: 0o600 });
    fs.renameSync(temporary, cache);
    return { ...result, disposition: 'built', key };
  } finally {
    fs.closeSync(descriptor);
    const current = fs.lstatSync(lock, { throwIfNoEntry: false });
    if (current?.dev === owner.dev && current.ino === owner.ino && current.isFile()) fs.unlinkSync(lock);
  }
}

/** Provision only a fixed local build tool, using empty configs and no inherited npm credentials. */
export async function prepareLocalReleaseSdk(): Promise<any> {
  const node = fs.realpathSync(process.execPath), build = ownedBuildRoot(service);
  const tooling = path.join(build, `release-sdk-tooling-pnpm-${RELEASE_SDK_PNPM_VERSION}`);
  fs.mkdirSync(tooling, { recursive: true });
  if (fs.lstatSync(tooling).isSymbolicLink() || fs.realpathSync(tooling) !== tooling) throw new Error('SDK tooling directory must be owned.');
  const user = path.join(tooling, 'user.npmrc'), global = path.join(tooling, 'global.npmrc');
  for (const file of [user, global]) {
    if (!fs.existsSync(file)) fs.writeFileSync(file, '', { flag: 'wx', mode: 0o600 });
    if (regular(file).length) throw new Error('SDK tooling npm config must remain empty.');
  }
  fs.mkdirSync(path.join(tooling, 'tmp'), { recursive: true });
  const env = releaseSdkEnvironment(node, user, global);
  const pnpm = path.join(tooling, 'node_modules/pnpm/bin/pnpm.cjs');
  if (!fs.existsSync(pnpm)) {
    console.error(`[dsh-sdk] install local pnpm ${RELEASE_SDK_PNPM_VERSION}`);
    installSdkDependencies(node, [resolvePeerNpm(node), 'install', '--prefix', tooling, '--ignore-scripts', '--no-audit', '--no-fund',
      '--package-lock=false', `pnpm@${RELEASE_SDK_PNPM_VERSION}`], service, { ...env, NPM_CONFIG_REGISTRY: downloadRegistry() },
    (executable, args, options) => execFileSync(executable, args, { cwd: options.cwd, env: options.env, encoding: 'utf8', timeout: 300_000, maxBuffer: 16 * 1024 * 1024 }));
  }
  return ensureReleaseSdk({ node, pnpm });
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.length !== 2) throw new Error('Usage: ensure-release-sdk.ts');
  console.log(JSON.stringify(await prepareLocalReleaseSdk()));
}
