import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {DatabaseSync} from 'node:sqlite';
import {ProgrammaticCredentials} from '../../src/persistence/programmatic-credentials.ts';

test('credential takeover preserves the old ID, digest and token path, rejects old writers and retains invisible source scopes', t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'harness-credentials-'));
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const directory=path.join(root,'programmatic-access');fs.mkdirSync(directory,{mode:0o700});
  const file=path.join(directory,'credentials.sqlite'),old=new DatabaseSync(file);
  t.after(()=>old.close());
  old.exec('CREATE TABLE credentials(id TEXT PRIMARY KEY,digest TEXT UNIQUE NOT NULL,metadata TEXT NOT NULL)');
  const token='brp_'+'a'.repeat(43),digest=createHash('sha256').update(token).digest('hex');
  const tokenFile=path.join(directory,'old.token');fs.writeFileSync(tokenFile,token+'\n',{mode:0o600});
  const original={id:'old-id',name:'old credential',workspaceIds:['same'],scopes:['read','execute'],allowFullAccess:false,revision:'legacy',createdAt:'old-time',revokedAt:null,tokenFilePath:tokenFile,unknownFutureSetting:{retain:true}};
  old.prepare('INSERT INTO credentials VALUES(?,?,?)').run(original.id,digest,JSON.stringify(original));
  const store=new ProgrammaticCredentials(root);
  assert.equal(store.authenticate('Bearer '+token).id,original.id);
  assert.equal(store.list()[0]!.tokenFilePath,tokenFile);
  assert.equal(old.prepare('SELECT digest FROM credentials').get()!.digest,digest);
  assert.throws(()=>old.prepare('UPDATE credentials SET metadata=?').run('{}'),/harness_credential_writer/,'the unmodified old direct connection cannot write after takeover');
  const registered=[{sourceId:'buildr',id:'same'},{sourceId:'harness-local',id:'directory-ref'}];
  const edited=store.update(original.id,'legacy',{name:'all sources',executionScopes:registered,scopes:['read','execute']},registered);
  assert.deepEqual(edited.executionScopes,registered);assert.deepEqual(edited.workspaceIds,['same']);
  const legacy=store.update(original.id,edited.revision,{name:'legacy edit',workspaceIds:['same'],scopes:['read']},['same']);
  assert.ok(legacy.executionScopes!.some(ref=>ref.sourceId==='harness-local'&&ref.id==='directory-ref'));
  assert.deepEqual(JSON.parse(old.prepare('SELECT metadata FROM credentials').get()!.metadata as string).unknownFutureSetting,{retain:true});
  const before=old.prepare('SELECT * FROM credentials').all();
  assert.throws(()=>store.update(original.id,legacy.revision,{name:'raw path',executionScopes:[{sourceId:'harness-local',id:'/arbitrary/path'}],scopes:['read']},registered),{code:'programmatic_input_invalid'});
  assert.deepEqual(old.prepare('SELECT * FROM credentials').all(),before);
  const regenerated=store.regenerate(original.id,legacy.revision);
  assert.equal(regenerated.credential.id,original.id);assert.notEqual(regenerated.token,token);
  assert.equal(fs.statSync(regenerated.credential.tokenFilePath!).mode&0o777,0o600);
  assert.equal(fs.readFileSync(tokenFile,'utf8'),token+'\n','prior secret files are not overwritten');
  assert.throws(()=>store.authenticate('Bearer '+token),{code:'programmatic_unauthorized'});
  assert.equal(store.authenticate('Bearer '+regenerated.token).id,original.id);
  store.revoke(original.id,regenerated.credential.revision);
  assert.throws(()=>store.authenticate('Bearer '+regenerated.token),{code:'programmatic_unauthorized'});
  assert.equal(fs.readFileSync(file).includes(Buffer.from(regenerated.token)),false);
});
