import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { normalizeFilesystemPath, sameFilesystemPath } from '../../../infrastructure/filesystem/filesystem-path-identity.ts';
import { CODE_LIMITS, codeFailure, relativeCodePath } from './code-file-reader.ts';

export const EDITABLE_FILE_BYTES = CODE_LIMITS.textBytes;
export const EDITABLE_FILE_JSON_BYTES = EDITABLE_FILE_BYTES * 6 + 64 * 1024;
export type ProtectedFileRange = { from: number; to: number };
export type EditableFileLocation = { rootPath: string; path: string; sourceRevision: string; locationLabel: string; versionLabel: string };
export type FileReadOnlyPolicy = { code: string; message: string } | null;
const digest = (value: string | Buffer) => crypto.createHash('sha256').update(value).digest('hex');
export const editableFileId = (file: string) => 'file-' + digest(normalizeFilesystemPath(file));

export function fileEditingFailure(code: string, message: string, status = 400, details?: unknown) {
  return Object.assign(codeFailure(code, message, status), details === undefined ? {} : { details });
}
function missing() { return fileEditingFailure('file_missing', '文件当前不存在，请保留输入并重新核对位置。', 404); }
function changed() { return fileEditingFailure('file_changed_during_read', '读取期间文件已变化，请重试。', 409); }

/** No symlink segment is accepted for editing, including a root replaced after observation. */
export function plainEditablePath(location: EditableFileLocation) {
  relativeCodePath(location.path);
  const root = path.resolve(location.rootPath);
  if (root.split(path.sep).some(segment => segment.toLowerCase() === '.git')) throw fileEditingFailure('file_path_forbidden', 'Git 管理目录不能编辑。', 403);
  let current = root;
  const rootStat = fs.lstatSync(root, { bigint: true, throwIfNoEntry: false });
  if (!rootStat?.isDirectory() || rootStat.isSymbolicLink() || !sameFilesystemPath(fs.realpathSync(root), root)) throw fileEditingFailure('file_source_changed', '来源目录已变化，请重新打开文件。', 409);
  for (const [index, segment] of location.path.split('/').entries()) {
    current = path.join(current, segment);
    const stat = fs.lstatSync(current, { bigint: true, throwIfNoEntry: false });
    if (!stat) throw missing();
    if (stat.isSymbolicLink()) throw fileEditingFailure('file_path_forbidden', '符号链接及其目录中的文件不能直接编辑。', 403);
    if (index < location.path.split('/').length - 1 && !stat.isDirectory()) throw fileEditingFailure('file_path_forbidden', '文件路径经过非普通目录。', 403);
  }
  const canonical = fs.realpathSync(current);
  if (!sameFilesystemPath(canonical, current)) throw fileEditingFailure('file_path_forbidden', '文件实际位置已变化。', 403);
  return canonical;
}

function stamp(stat: fs.BigIntStats) { return [stat.dev, stat.ino, stat.size, stat.mtimeNs, stat.ctimeNs, stat.mode, stat.nlink].join(':'); }
export function editableSourceRevision(rootPath: string, identity: unknown) {
  const root = fs.lstatSync(rootPath, { bigint: true });
  if (!root.isDirectory() || root.isSymbolicLink()) throw fileEditingFailure('file_source_changed', '来源目录不是普通目录。', 409);
  return 'source-' + digest(JSON.stringify([normalizeFilesystemPath(rootPath), String(root.dev), String(root.ino), identity]));
}

function managedRanges(content: string): { ranges: ProtectedFileRange[]; valid: boolean } {
  const marker = /^<!-- buildr:required (begin|end) -->\r?$/gm;
  const ranges: ProtectedFileRange[] = [];
  let start: number | null = null;
  if ([...content.matchAll(/^<!-- buildr:required[^\r\n]*$/gm)].length !== [...content.matchAll(marker)].length) return { ranges: [], valid: false };
  for (const match of content.matchAll(marker)) {
    if (match[1] === 'begin') { if (start !== null) return { ranges: [], valid: false }; start = match.index; }
    else { if (start === null) return { ranges: [], valid: false }; ranges.push({ from: start, to: match.index + match[0].length - Number(match[0].endsWith('\r')) }); start = null; }
  }
  return { ranges, valid: start === null };
}
function generatedHeader(content: string) {
  return /^(?:\uFEFF)?(?:---\r?\n[\s\S]*?\r?\n---\r?\n)?\s*<!-- Generated by Buildr\./.test(content);
}

/** Complete UTF-8 source read; byte identity includes metadata to detect replacement and ABA edits. */
export function readEditableFile(location: EditableFileLocation, policy: (file: string) => FileReadOnlyPolicy = () => null) {
  const file = plainEditablePath(location);
  const descriptor = fs.openSync(file, fs.constants.O_RDONLY | fs.constants.O_NOFOLLOW | fs.constants.O_NONBLOCK);
  try {
    const before = fs.fstatSync(descriptor, { bigint: true });
    if (!before.isFile()) throw fileEditingFailure('file_type_unsupported', '当前路径不是普通文件。');
    const sizeBytes = Number(before.size);
    let content = '', bytes = Buffer.alloc(0), readonly: FileReadOnlyPolicy = null;
    if (sizeBytes > EDITABLE_FILE_BYTES) readonly = { code: 'file_too_large', message: '文件超过 5 MiB，保持只读阅读。' };
    else {
      bytes = Buffer.alloc(sizeBytes + 1); let length = 0;
      while (length < bytes.length) { const count = fs.readSync(descriptor, bytes, length, bytes.length - length, null); if (!count) break; length += count; }
      if (length !== sizeBytes) throw changed();
      bytes = bytes.subarray(0, length);
      try { content = new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(bytes); }
      catch { readonly = { code: 'file_encoding_unsupported', message: '文件不是完整 UTF-8 文本，保持只读。' }; }
      if (bytes.includes(0)) { content = ''; readonly = { code: 'file_binary', message: '二进制文件保持只读。' }; }
    }
    const after = fs.fstatSync(descriptor, { bigint: true });
    const named = fs.lstatSync(plainEditablePath(location), { bigint: true });
    if (stamp(before) !== stamp(after) || stamp(before) !== stamp(named)) throw changed();
    const managed = managedRanges(content);
    let writable = Boolean(before.mode & 0o222n);
    try { fs.accessSync(file, fs.constants.W_OK); } catch { writable = false; }
    readonly ||= !managed.valid ? { code: 'file_managed_block_invalid', message: '受管区块（Managed Block）标记不完整，请先由 Buildr 恢复。' }
      : generatedHeader(content) ? { code: 'file_generated', message: '此文件由 Buildr 生成，请修改对应来源。' }
      : before.nlink > 1n ? { code: 'file_hard_link', message: '文件有多个硬链接（Hard Link），请在原维护入口修改。' }
      : !writable ? { code: 'file_not_writable', message: '当前文件没有写入权限，保持只读。' }
      : policy(file);
    const revision = 'file-' + digest(stamp(before) + '\0' + digest(bytes));
    return { file, mode: Number(before.mode & 0o7777n), snapshot: {
      fileId: editableFileId(file), absolutePath: file, ...location, version: location.versionLabel,
      kind: readonly?.code === 'file_binary' || readonly?.code === 'file_encoding_unsupported' || sizeBytes > EDITABLE_FILE_BYTES ? 'unsupported' as const : location.path.toLowerCase().endsWith('.md') ? 'markdown' as const : 'text' as const,
      content, revision, sizeBytes, editable: readonly === null, readonlyReason: readonly?.message ?? null, readonlyReasonCode: readonly?.code ?? null,
      protectedRanges: managed.ranges, observedAt: new Date().toISOString(),
    } };
  } finally { fs.closeSync(descriptor); }
}

export function assertEditableContent(before: ReturnType<typeof readEditableFile>['snapshot'], content: string) {
  if (!before.editable) throw fileEditingFailure('file_read_only', before.readonlyReason || '此文件保持只读。', 403);
  if (typeof content !== 'string' || content.includes('\0') || Buffer.from(content, 'utf8').toString('utf8') !== content) throw fileEditingFailure('file_content_invalid', '保存内容必须是完整 UTF-8 文本。');
  if (Buffer.byteLength(content, 'utf8') > EDITABLE_FILE_BYTES) throw fileEditingFailure('file_too_large', '保存内容超过 5 MiB。', 413);
  const next = managedRanges(content);
  const oldBlocks = before.protectedRanges.map(range => before.content.slice(range.from, range.to));
  const newBlocks = next.ranges.map(range => content.slice(range.from, range.to));
  if (!next.valid || JSON.stringify(oldBlocks) !== JSON.stringify(newBlocks)) throw fileEditingFailure('file_managed_block_changed', '受管区块（Managed Block）不能修改；请保留原文，仅编辑区块外内容。', 403);
}

/** A final synchronous recheck narrows external-writer races; rename is not cross-process compare-and-swap. */
export function replaceEditableFile(file: string, content: string, mode: number, recheck: () => void) {
  const temporary = path.join(path.dirname(file), `.${path.basename(file)}.buildr-edit-${crypto.randomUUID()}`);
  let descriptor: number | null = null;
  try {
    descriptor = fs.openSync(temporary, fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL | fs.constants.O_NOFOLLOW, mode);
    fs.writeFileSync(descriptor, content, 'utf8');
    fs.fchmodSync(descriptor, mode);
    fs.fsyncSync(descriptor);
    recheck();
    fs.renameSync(temporary, file);
  } finally {
    if (descriptor !== null) fs.closeSync(descriptor);
    try { fs.unlinkSync(temporary); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
  }
}
