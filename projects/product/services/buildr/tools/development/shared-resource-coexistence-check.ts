import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRuntime, runtimeProvide } from '../../src/bootstrap/runtime.ts';
import { WORKSPACE_APPLICATION } from '../../src/modules/workspace/module.ts';
import { ensurePackageResources, publishPackageResources, readResourceAdoption, sharedResourcesRoot } from '../../src/infrastructure/product-resources/shared-resources.ts';
const sandbox=process.env.BUILDR_SMOKE_ROOT!;let root=process.env.BUILDR_SMOKE_WORKSPACE_ROOT!;
assert.ok(sandbox&&root,'Use the isolated check runner.');
const service=path.resolve(import.meta.dirname,'../..');
process.env.BUILDR_NPM_ENTRY_PATH=path.join(service,'bin/buildr.mjs');
fs.mkdirSync(root,{recursive:true});root=fs.realpathSync(root);
const initialized=spawnSync(process.execPath,[process.env.BUILDR_NPM_ENTRY_PATH,'init','--target',root,'--name','Resource coexistence','--description','Shared projection recovery'],{encoding:'utf8'});
assert.equal(initialized.status,0,initialized.stderr||initialized.stdout);
const candidate=path.join(sandbox,'resource-publisher');
fs.mkdirSync(candidate);fs.copyFileSync(path.join(service,'package.json'),path.join(candidate,'package.json'));
fs.cpSync(path.join(service,'resources'),path.join(candidate,'resources'),{recursive:true});
fs.appendFileSync(path.join(candidate,'resources/runtime/skills/buildr/SKILL.md'),'\nShared projection recovery marker.\n');
const before=readResourceAdoption(root)!;
const current=publishPackageResources(candidate,{expectedId:before.resourceSet});assert.notEqual(before.resourceSet,current.id);
assert.equal(ensurePackageResources(service).id,current.id,'Old consumer cannot republish.');
const ownSource=fs.readFileSync(path.join(root,'AGENTS.md'),'utf8');
const runtime=createRuntime();const app:any=runtimeProvide(runtime,WORKSPACE_APPLICATION);
const entry=app.listRegisteredWorkspaces().workspaces.find((item:any)=>item.rootPath===fs.realpathSync(root));assert.ok(entry?.workspace?.id,JSON.stringify(app.listRegisteredWorkspaces()));
const opened=app.prepareWorkspaceForOpen(entry.workspace.id);
assert.equal(opened.ready,true);assert.equal(opened.resourceRefresh.status,'refreshed',opened.resourceRefresh.message);
assert.match(fs.readFileSync(path.join(root,'.agents/skills/buildr/SKILL.md'),'utf8'),/Shared projection recovery marker/);
assert.equal(readResourceAdoption(root)?.resourceSet,current.id);
assert.equal(app.listRegisteredWorkspaces().workspaces.find((item:any)=>item.workspace?.id===entry.workspace.id)?.readiness,'ready');
assert.equal(fs.readFileSync(path.join(root,'AGENTS.md'),'utf8'),ownSource);
assert.equal(fs.readFileSync(path.join(sharedResourcesRoot(),'skills/product/buildr/SKILL.md'),'utf8').includes('Shared projection recovery marker'),true);
console.log(JSON.stringify({status:'passed',scenarios:['old consumer','actual runtime refresh','source preservation','adoption']}));
